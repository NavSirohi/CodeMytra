import JSZip from "jszip";
import path from "path";
import { prisma } from "@/lib/db";
import { sanitizeProjectFiles } from "@/server/orchestration/revisions";

export interface GenerateProjectZipOptions {
  projectId: string;
  revisionId?: string;
  userId: string;
}

/**
 * Generates a clean, validated ZIP archive of a project's revision.
 * Enforces server-side authorization and strict Zip Slip protection.
 */
export async function generateProjectZip(options: GenerateProjectZipOptions) {
  const { projectId, revisionId, userId } = options;

  // 1. Authenticate & verify project ownership
  const project = await prisma.project.findUnique({
    where: { id: projectId, userId },
    select: { id: true, name: true, currentRevisionId: true },
  });

  if (!project) {
    throw new Error("Project not found or unauthorized");
  }

  // 2. Resolve revision
  const targetRevId = revisionId || project.currentRevisionId;

  const revision = targetRevId
    ? await prisma.projectRevision.findUnique({
        where: { id: targetRevId, projectId },
      })
    : await prisma.projectRevision.findFirst({
        where: { projectId },
        orderBy: { revisionNumber: "desc" },
      });

  if (!revision) {
    throw new Error("No revision available to export for this project");
  }

  const rawFiles = (revision.files as Record<string, string>) || {};
  const cleanFiles = sanitizeProjectFiles(rawFiles);

  const zip = new JSZip();

  // Root folder inside the zip for clean extraction
  const rootFolderName = `codemytra-${project.name || "project"}-v${revision.revisionNumber}`;
  const folder = zip.folder(rootFolderName);

  if (!folder) {
    throw new Error("Failed to initialize zip directory");
  }

  let hasReadme = false;

  for (const [filePath, content] of Object.entries(cleanFiles)) {
    // Security: strict Zip Slip defense
    const normalized = path.normalize(filePath).replace(/^(\.\/|\/)/, "");
    if (normalized.includes("..") || path.isAbsolute(filePath)) {
      continue;
    }

    if (normalized.toLowerCase() === "readme.md") {
      hasReadme = true;
    }

    folder.file(normalized, content);
  }

  // Ensure standalone configuration files are present and valid
  const hasPackageJson = Object.keys(cleanFiles).some(
    (f) => path.normalize(f).replace(/^(\.\/|\/)/, "").toLowerCase() === "package.json"
  );
  if (!hasPackageJson) {
    const defaultPackageJson = JSON.stringify(
      {
        name: (project.name || "codemytra-app")
          .toLowerCase()
          .replace(/[^a-z0-9_-]/g, "-")
          .replace(/^-+|-+$/g, "") || "codemytra-app",
        version: "0.1.0",
        private: true,
        scripts: {
          dev: "next dev",
          build: "next build",
          start: "next start",
        },
        dependencies: {
          next: "16.2.9",
          react: "19.2.4",
          "react-dom": "19.2.4",
          "lucide-react": "^1.21.0",
          clsx: "^2.1.1",
          "tailwind-merge": "^3.0.1",
        },
        devDependencies: {
          typescript: "^5.7.3",
          "@types/node": "^22.0.0",
          "@types/react": "^19.0.0",
          "@types/react-dom": "^19.0.0",
          tailwindcss: "^4.0.0",
        },
      },
      null,
      2
    );
    folder.file("package.json", defaultPackageJson);
  }

  const hasTsConfig = Object.keys(cleanFiles).some(
    (f) => path.normalize(f).replace(/^(\.\/|\/)/, "").toLowerCase() === "tsconfig.json"
  );
  if (!hasTsConfig) {
    const defaultTsConfig = JSON.stringify(
      {
        compilerOptions: {
          target: "ES2017",
          lib: ["dom", "dom.iterable", "esnext"],
          allowJs: true,
          skipLibCheck: true,
          strict: true,
          noEmit: true,
          esModuleInterop: true,
          module: "esnext",
          moduleResolution: "bundler",
          resolveJsonModule: true,
          isolatedModules: true,
          jsx: "preserve",
          incremental: true,
          plugins: [{ name: "next" }],
          paths: { "@/*": ["./*"] },
        },
        include: ["next-env.d.ts", "**/*.ts", "**/*.tsx", ".next/types/**/*.ts"],
        exclude: ["node_modules"],
      },
      null,
      2
    );
    folder.file("tsconfig.json", defaultTsConfig);
  }

  const hasNextConfig = Object.keys(cleanFiles).some((f) => {
    const norm = path.normalize(f).replace(/^(\.\/|\/)/, "").toLowerCase();
    return norm === "next.config.ts" || norm === "next.config.mjs" || norm === "next.config.js";
  });
  if (!hasNextConfig) {
    folder.file("next.config.ts", "import type { NextConfig } from 'next';\n\nconst nextConfig: NextConfig = {};\n\nexport default nextConfig;\n");
  }

  // Include default README if user project didn't generate one
  if (!hasReadme) {
    const defaultReadme = `# ${project.name || "CodeMytra Application"} (Revision ${revision.revisionNumber})

Generated by **CodeMytra** AI Application Builder.

## Getting Started

1. Install dependencies:
\`\`\`bash
npm install
\`\`\`

2. Run the development server:
\`\`\`bash
npm run dev
\`\`\`

Open [http://localhost:3000](http://localhost:3000) with your browser to view the application.
`;
    folder.file("README.md", defaultReadme);
  }

  const buffer = await zip.generateAsync({
    type: "nodebuffer",
    compression: "DEFLATE",
    compressionOptions: { level: 6 },
  });

  const filename = `${rootFolderName}.zip`;

  return {
    filename,
    buffer,
    revisionNumber: revision.revisionNumber,
    fileCount: Object.keys(cleanFiles).length,
  };
}
